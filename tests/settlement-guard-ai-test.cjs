'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const game=fs.readFileSync(path.join(__dirname,'..','game','game.js'),'utf8');
const relations=fs.readFileSync(path.join(__dirname,'..','game','world-expansion.js'),'utf8');
assert.match(game,/isSettlementGuard:true/,'each village must receive patrol guard NPCs');
assert.match(game,/posts=\[\[-410,-150\],\[0,390\],\[410,-150\]\]/,'each settlement must have three separate patrol posts');
assert.match(game,/function updateVillageNpcs\(dt\)/,'guard AI must run through the village NPC simulation');
assert.match(game,/npc\.activity='patrol'/,'guards must patrol when the settlement is not hostile');
assert.match(game,/npc\.activity=retaliation\?'response-raid':'pursuing'/,'wanted players must be hunted and high wanted must trigger a response raid');
assert.match(game,/retaliation\?12:8/,'response raid guards must deal stronger damage than ordinary pursuit');
assert.match(game,/relation\.allied===true&&wanted===0/,'allied defenders must only support valid alliance holders');
assert.match(game,/npc\.activity='defending'/,'allied guards must defend against event enemies');
assert.match(relations,/const VERSION = 3/,'relation state must be versioned for alliance migration');
assert.match(relations,/allied:value\.allied===true/,'alliance state must survive migration and reload');
assert.match(relations,/function establishVillageAlliance\(villageId\)/,'player must be able to conclude an explicit alliance');
assert.match(relations,/record\.trust<75\|\|record\.wanted>0/,'alliance requires trust 75 and no active wanted level');
assert.match(relations,/spendGold\?\.\(50\)/,'alliance must cost actual gold');
assert.match(relations,/record\.allied=false/,'serious crimes must revoke an existing alliance');
assert.match(relations,/establish-village-alliance/,'chronicles UI must expose the alliance action');
console.log('Settlement guard AI tests passed: patrols, wanted pursuit, response raids, allied combat support and persistent treaties.');
