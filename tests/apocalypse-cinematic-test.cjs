'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'game/index.html'), 'utf8');
const game = fs.readFileSync(path.join(root, 'game/game.js'), 'utf8');
const scene = fs.readFileSync(path.join(root, 'game/apocalypse-cinematic.js'), 'utf8');
assert.match(html, /<script src="apocalypse-cinematic\.js"><\/script>\s*<script src="game\.js"><\/script>/, 'cinematic must load before game runtime');
assert.match(game, /window\.ApocalypseCinematic&&typeof window\.ApocalypseCinematic\.play==='function'/, 'Apocalypse Play must start the opening before entering the shelter');
assert.match(scene, /const TOTAL=50\.1,BLACK_IN=16,BLACK_HOLD=17\.5,ZOMBIES_AT=21\.1,DESCENT_AT=45\.1/, 'cinematic timing must retain the agreed sequence');
assert.match(scene, /function heli\(/, 'helicopter sequence must exist');
assert.match(scene, /function person\(/, 'procedural zombie and mutant models must exist');
assert.match(scene, /const DIALOGUES=\[/, 'cinematic dialogue timeline must exist');
assert.match(scene, /speechSynthesis\.speak\(u\)/, 'spoken dialogue must play when browser speech is available');
assert.match(scene, /function chooseRussianVoice\(/, 'voice selection must prefer available Russian voices');
assert.match(scene, /function radioBurst\(/, 'radio dialogue must have dedicated interference bursts');
assert.match(scene, /u\.onstart[\s\S]*u\.onend/, 'radio transmission must have start and end sound cues');
assert.match(scene, /Microsoft.*Irina|Google.*русский/, 'natural Russian system voice candidates must be preferred when installed');
assert.match(scene, /ЗАРАЖЁННЫЙ[\s\S]*МУТАНТ[\s\S]*ДИСПЕТЧЕР/, 'infected, mutant and dispatcher dialogue must be present');
assert.match(scene, /speaking\?\(/, 'speaking character mouth animation must be present');
assert.match(scene, /a:14,b:17\.5/, 'infected camera sequence must include multiple angles');
assert.match(scene, /a:14\.8,b:16/, 'helicopter camera choreography must include rapid angle changes');
assert.match(scene, /fired\.growl2[\s\S]*fired\.growl3[\s\S]*fired\.base[\s\S]*fired\.tunnel/, 'several creature and underground sound cues must exist');
console.log('Apocalypse cinematic integration checks passed.');
