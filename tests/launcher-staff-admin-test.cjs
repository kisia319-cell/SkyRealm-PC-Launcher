'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const app=fs.readFileSync('app.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('style.css','utf8');
assert.ok(html.includes('id="staff-admin-panel"'),'Admin panel must exist in launcher settings');
assert.ok(html.includes('id="staff-player-select"')&&html.includes('id="staff-role-select"'),'Role assignment controls must exist');
assert.ok(html.includes('id="staff-duration-select"'),'Role duration selector must exist');
assert.ok(html.includes('id="staff-grant-role"')&&html.includes('id="staff-revoke-role"'),'Grant and revoke controls must exist');
assert.ok(html.includes('id="staff-public-grants-toggle"'),'Public role grant control must exist');
assert.match(app,/skyrealm-auth', 'skyrealm-staff'/,'Staff API must use its dedicated server function');
assert.match(app,/requestStaff\('\/api\/staff\/me'/,'Launcher must ask the server to verify the signed-in role');
assert.match(app,/if\(me\.role!=='admin'\)return/,'Non-admin users must not see the admin panel');
assert.match(app,/requestStaff\('\/api\/staff\/players'/,'Player list must come from the protected staff API');
assert.match(app,/requestStaff\('\/api\/staff\/grants'/,'Role grants must go through the protected server API');
assert.match(app,/requestStaff\('\/api\/staff\/settings'/,'Open grants setting must be changed through the protected server API');
assert.match(app,/getValidToken\(\)/,'Staff API calls must use a refreshed authenticated session');
assert.match(app,/Нельзя снять собственную роль администратора/,'Admin UI must guard against accidental self-revocation');
assert.match(app,/Локальный режим администратора/,'Local test toggle must not be described as server admin access');
assert.ok(css.includes('.staff-admin-panel')&&css.includes('.staff-player-row'),'Admin section must have dedicated responsive styles');
console.log('Launcher server-admin UI and authorization integration tests passed.');
