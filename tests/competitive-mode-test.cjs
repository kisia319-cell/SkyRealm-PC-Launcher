'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const launcherHtml = read('index.html');
const app = read('app.js');
const launcherPy = read('launcher.py');
const build = read('build_exe.bat');
const primeHtml = read('game/competitive/index.html');
const primeJs = read('game/competitive/prime-world.js');

assert.match(launcherHtml, /data-page="competitive"/);
assert.match(launcherHtml, /id="page-competitive"/);
assert.match(launcherHtml, /id="play-competitive"/);
assert.match(app, /launch_competitive_game/);
assert.match(app, /game\/competitive\/index\.html/);
assert.match(launcherPy, /def launch_competitive_game\(self\)/);
assert.match(launcherPy, /--prime-competitive/);
assert.match(launcherPy, /127\.0\.0\.1", 48732/);
assert.match(launcherPy, /PrimeLauncher.*webview-profile/s);
assert.match(build, /--name PrimeLauncher/);
assert.match(build, /prime_launcher_dist\\PrimeLauncher\.exe;bin/);
assert.match(primeHtml, /PRIME LAUNCHER/);
assert.match(primeHtml, /190 × 190/);
assert.match(primeJs, /const SIZE=190/);
assert.match(primeJs, /let player=\{x:95,y:95\}/);
assert.match(primeJs, /primeLauncher\.world\.v1/);
assert.match(primeJs, /Math\.max\(0,Math\.min\(SIZE-1/);
assert.doesNotMatch(primeJs, /game\.js|multiplayer-core|boss-realm/);
console.log('competitive-mode-test: all assertions passed');
