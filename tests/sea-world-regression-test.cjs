'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const sea=fs.readFileSync('game/sea-system.js','utf8');
const game=fs.readFileSync('game/game.js','utf8');
assert.match(sea,/w\/\(W\*TILE\*\.76\)/,'Sea camera scale must include tile size');
assert.match(sea,/if\(!state\.sharks\.length\)/,'Old sea saves must repopulate missing sharks');
assert.match(sea,/if\(!state\.monsters\.length\)/,'Old sea saves must repopulate missing sea monsters');
assert.match(sea,/Layered animated wave crests/,'Sea must render animated layered waves');
assert.match(sea,/Player's ship: hull, deck, mast/,'Sea must render a detailed visible ship');
assert.match(sea,/clearly visible sailor avatar/,'Sea must render the player character on deck');
assert.match(sea,/Sharks: animated bodies, tail, dorsal and pectoral fins/,'Sea must render recognizable animated sharks');
const start=game.indexOf('function giveResource(');
const end=game.indexOf('function healPlayer(',start);
assert.ok(start>=0&&end>start,'Admin/moderator item grant handler must exist');
const grant=game.slice(start,end);
assert.match(grant,/inventoryItems\.find/,'Grant must resolve a real catalog item');
assert.match(grant,/changeItem\(item\.name,granted\)/,'Grant must update the actual inventory item and item hooks');
assert.doesNotMatch(grant,/inventoryItems\.push/,'Grant must not create display-only fake items');
console.log('Sea world visuals and real admin item grant tests passed.');
