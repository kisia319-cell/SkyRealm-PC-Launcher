'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('game/index.html','utf8');
const game=fs.readFileSync('game/game.js','utf8');
const runtime=fs.readFileSync('game/custom-mods-runtime.js','utf8');
const launcher=fs.readFileSync('launcher.py','utf8');
assert.ok(html.includes('id="studio-install-shade"'));
assert.ok(html.includes('id="studio-install-yes"')&&html.includes('id="studio-install-no"'));
assert.ok(!html.includes('id="script-mod-studio"'),'Embedded editor modal must not remain in the game.');
assert.ok(game.includes("window.addEventListener('skyrealm:open-mod-studio',openSkyRealmStudio)"));
assert.ok(game.includes('nativeApi.check_mod_studio')&&game.includes('nativeApi.launch_mod_studio'));
assert.ok(game.includes('nativeApi.install_mod_studio()'));
assert.ok(runtime.includes("new CustomEvent('skyrealm:open-mod-studio')"));
assert.ok(launcher.includes('def check_mod_studio(self):'));
assert.ok(launcher.includes('def launch_mod_studio(self):'));
assert.ok(launcher.includes('def install_mod_studio(self):'));
assert.ok(launcher.includes('hashlib.sha256(temporary_data).hexdigest()'));
assert.ok(launcher.includes('digest.split(":", 1)[1]'));
assert.ok(launcher.includes('SkyRealm-Mod-Studio/releases/latest'));
console.log('SkyRealmStudio external launch, install prompt and SHA-256 verification checks passed.');
