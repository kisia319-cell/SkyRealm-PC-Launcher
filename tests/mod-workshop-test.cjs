'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const game=fs.readFileSync('game/game.js','utf8');
const html=fs.readFileSync('game/index.html','utf8');
new vm.Script(game,{filename:'game/game.js'});
assert.ok(game.includes("const MODS_STORAGE_KEY='skyrealm_installed_mods_v1'"),'Installed mods must persist across game restarts and updates');
assert.ok(game.includes('function readInstalledMods()')&&game.includes('function saveInstalledMods()'),'Mod install state must be validated and saved');
assert.ok(game.includes('function renderModCatalog()')&&game.includes('function toggleMod(id)'),'Catalog must render install/uninstall controls');
assert.ok(game.includes("document.getElementById('menu-mods').addEventListener('click',openModsCatalog)"),'Main menu must open the mod catalog');
assert.ok(html.includes('id="mods-catalog-shade"')&&html.includes('id="mods-catalog-list"'),'Mod catalog dialog must exist');
assert.ok(html.includes('id="close-mods-catalog"'),'Mod catalog must have a close control');
for(const id of ['cartographer','angler','green_thumb','miners_luck','survivalist'])assert.ok(game.includes("id:'"+id+"'"),'Missing mod '+id);
assert.ok(game.includes("radius=isModInstalled('cartographer')?5:3"),'Cartographer must change map reveal radius');
assert.ok(game.includes("fishingCastTimer=isModInstalled('angler')?2.2:3.2"),'Angler must shorten fishing time');
assert.ok(game.includes("isModInstalled('angler')?.08:0"),'Angler must improve pearl chance');
assert.ok(game.includes("(isModInstalled('green_thumb')?1.35:1)"),'Green Thumb must speed up crop growth');
assert.ok(game.includes("(isModInstalled('miners_luck')?0.15:0)"),'Miner Luck must improve bonus ore chance');
assert.ok(game.includes("isModInstalled('survivalist')?12:10"),'Survivalist must reduce hunger drain');
assert.ok(game.includes('MOD_CATALOG.some(mod=>mod.id===id)'),'Only known mod IDs may be restored from local storage');
assert.ok(html.includes('Установка и удаление не стирают миры и сохранения.'),'Catalog must explain save safety');
console.log('Mod workshop: five gameplay effects, persistent installs, catalog UI and save safety passed.');
