const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const game=fs.readFileSync(path.join(root,'game/game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'game/index.html'),'utf8');
assert.match(game,/function drawGrassTexture\(target,x,y,sx,sy,h,biome,quality\)/,'biome ground texture renderer exists');
assert.match(game,/function drawVillageSettlements\(camX,camY,time\)/,'trade settlement renderer exists');
const normal=game.match(/drawCabin\(camX,camY\);([^\n]+)drawQuarryOutpost/);
assert.ok(normal,'ordinary world cabin and quarry outpost remain');
assert.doesNotMatch(normal[1],/drawVillageSettlements|drawValleyHamlet|drawFences/,'ordinary world must not spawn villages, hamlets or cabin fence');
assert.match(game,/else if\(tradeWorldMode\)\{[\s\S]*?drawVillageSettlements\(camX,camY,time\)/,'settlements remain in trade world');
assert.match(game,/ctx\.scale\(1\.28,1\.28\)/,'player sprite scale reduced to a compact size');
assert.match(game,/ctx\.fillRect\(-4,-12,4,4\)/,'visible eyes restored');
assert.match(game,/ctx\.roundRect\(-13,-1,5,12,2\)/,'visible arms remain');
assert.doesNotMatch(game,/world\.fences\.push\(/,'no starting-home fence is seeded');
assert.match(game,/function drawMainRoads\(camX,camY\)/,'continuous roads remain');
assert.match(html,/<canvas id="world"/,'main world canvas remains present');
console.log('Visual renderer regression passed: villages only in trade world, original player scale, no cabin fence.');